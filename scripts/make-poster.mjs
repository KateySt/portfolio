// Generates app/poster.css: a tiny inline (data URI) copy of the robot poster.
// It paints with the very first frame, so the hero's LCP doesn't wait for an
// image request; the sharp <img> of the same size lands on top a moment later.
// Re-run after re-rendering public/robot-fallback.png:  node scripts/make-poster.mjs
import sharp from "sharp";
import { writeFile } from "node:fs/promises";

const WIDTH = 360;

const buf = await sharp("public/robot-fallback.png")
  .resize({ width: WIDTH })
  .webp({ quality: 62, alphaQuality: 80, effort: 6 })
  .toBuffer();

const css = `/* generated by scripts/make-poster.mjs — do not edit */
[data-robot-poster-bg] {
  background: url("data:image/webp;base64,${buf.toString("base64")}") center / contain no-repeat;
}
`;
await writeFile("app/poster.css", css);
console.log(`app/poster.css written: ${WIDTH}px webp, ${(buf.length / 1024).toFixed(1)} KB`);
